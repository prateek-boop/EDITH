import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
async function enter(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Continue in local demo mode', exact: true }).click()
  await page.locator('.recent-row').first().click()
  await expect(page.getByRole('heading', { name: 'What are we building today?' })).toBeVisible()
}
const violations = async (page: Page) => (await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)}))
test('entry and all workspace views are accessible', async ({ page }) => {
  await page.goto('/'); expect(await violations(page)).toEqual([])
  await page.getByRole('button', { name: 'Continue in local demo mode', exact: true }).click()
  expect(await violations(page)).toEqual([])
  await page.locator('.recent-row').first().click()
  await expect(page.locator('.idle-copy')).toBeVisible()
  for (const label of ['EDITH Agent','Workspace','Graph','Memory','Activity']) {
    await page.getByRole('button',{name:label,exact:true}).click()
    await page.locator('.view-loader').waitFor({state:'hidden'})
    await page.waitForTimeout(400)
    expect(await violations(page), label).toEqual([])
    await expect(page.locator('.recovery-state')).toHaveCount(0)
  }
})
test('responsive navigation and no page overflow', async ({ page }) => {
  test.setTimeout(90000) // Thirty view transitions include software-rendered WebGL in CI.
  await enter(page)
  for (const [width,height] of [[1440,1000],[1024,768],[768,1024],[390,844],[320,568],[844,390]]) {
    await page.setViewportSize({width,height})
    for (const label of ['EDITH Agent','Workspace','Graph','Memory','Activity']) {
      await page.getByRole('button',{name:label,exact:true}).click()
      await expect(page.getByRole('button',{name:label,exact:true})).toBeInViewport()
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${width} ${label}`).toBe(true)
    }
  }
})
